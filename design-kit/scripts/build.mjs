/**
 * Builds the kit into dist/:
 *   moddy.css       the whole design system, with the fonts next to it
 *   theme-boot.js   the blocking <head> script (theme before paint, booting)
 *   moddy.js        the components and helpers, one self-contained module
 *   demo.js         the demo page's script (demo/index.html)
 *
 * First it regenerates, from src/theme/seeds.ts:
 *   src/theme/palettes.ts       every seed's theme, light and dark, for the
 *                               boot script (no color math before paint)
 *   src/css/theme-fallback.css  the default theme, for pages without JS
 * Both are committed, so the sources also build without this script.
 *
 *   node scripts/build.mjs           build once
 *   node scripts/build.mjs --serve   rebuild on change, serve on :8000
 */

import {writeFile} from 'node:fs/promises';
import * as esbuild from 'esbuild';

const serve = process.argv.includes('--serve');
const header = '/* Generated by scripts/build.mjs from src/theme/seeds.ts: do not edit. */\n';

async function generateThemes() {
  // Runs src/theme/scheme.ts and seeds.ts in Node, bundled on the fly.
  const {outputFiles} = await esbuild.build({
    stdin: {
      contents: "export {themeCss, themeTokens} from './src/theme/scheme.ts'; export {SEEDS, DEFAULT_SEED} from './src/theme/seeds.ts';",
      resolveDir: process.cwd(),
      loader: 'ts',
    },
    bundle: true,
    format: 'esm',
    platform: 'node',
    write: false,
  });
  const source = Buffer.from(outputFiles[0].contents).toString('base64');
  const {themeCss, themeTokens, SEEDS, DEFAULT_SEED} = await import(`data:text/javascript;base64,${source}`);

  const palettes = SEEDS.map((seed) => ({seed, light: themeCss(seed, false), dark: themeCss(seed, true)}));
  await writeFile(
    'src/theme/palettes.ts',
    `${header}\nexport const PALETTES: Array<{seed: string; light: string; dark: string}> = ${JSON.stringify(palettes, null, 2)};\n`,
  );

  const declarations = (tokens) => tokens.split(';').filter(Boolean).map((d) => `    ${d};`).join('\n');
  await writeFile(
    'src/css/theme-fallback.css',
    `${header}
/* The default theme (${DEFAULT_SEED}) for pages without JS. In a layer: the
   theme the boot script applies is unlayered, so it always wins. */
@layer moddy-fallback {
  :root {
${declarations(themeTokens(DEFAULT_SEED, false))}
  }

  @media (prefers-color-scheme: dark) {
    :root {
${declarations(themeTokens(DEFAULT_SEED, true))}
    }
  }
}
`,
  );
}

await generateThemes();

const common = {
  bundle: true,
  minify: !serve,
  sourcemap: serve,
  logLevel: 'info',
  target: ['es2022', 'chrome111', 'firefox113', 'safari16.4'],
};

const builds = [
  {
    ...common,
    entryPoints: {moddy: 'src/css/moddy.css'},
    outdir: 'dist',
    loader: {'.woff2': 'file'},
    assetNames: 'fonts/[name]',
  },
  {...common, entryPoints: {'theme-boot': 'src/theme/boot.ts'}, outdir: 'dist', format: 'iife'},
  {...common, entryPoints: {moddy: 'src/index.ts', demo: 'demo/demo.ts'}, outdir: 'dist', format: 'esm'},
];

if (serve) {
  const contexts = await Promise.all(builds.map((options) => esbuild.context(options)));
  await Promise.all(contexts.map((context) => context.watch()));
  const {port} = await contexts[2].serve({servedir: '.', port: 8000});
  console.log(`Demo: http://localhost:${port}/demo/`);
} else {
  await Promise.all(builds.map((options) => esbuild.build(options)));
}
